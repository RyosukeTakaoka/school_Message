## 第4条(暗号化の仕組みと、その効果・限界)

### 4.1 鍵の生成と保管

- 初めてプロフィールを登録した時点で、その端末内で Curve25519(X25519)の鍵ペアが生成されます
- **公開鍵**のみが CloudKit に保存されます
- **秘密鍵**は端末の Keychain に保存されます。CloudKit には送信されず、開発者は取得できません
- 秘密鍵は iCloud キーチェーンを通じて同一 Apple ID の他の端末に同期されます。これにより機種変更後も過去の会話を読めます

### 4.2 会話ごとの鍵

会話ごとにランダムな 256 ビットの共通鍵が生成され、参加者一人ひとりの公開鍵で個別に封緘されて保存されます。各参加者は自分の秘密鍵でのみ、自分宛の会話鍵を取り出せます。

### 4.3 メッセージの暗号化

本文とメディアは、会話鍵を用いて AES-GCM(認証付き暗号)で暗号化されてから送信されます。

### 4.4 この仕組みによって守られること

- 開発者はメッセージのレコードを閲覧できますが、**中身は意味をなさない暗号文であり、復号できません**
- 会話に参加していない第三者は、データを取得できたとしても本文を読めません
- サーバー(Apple)も会話鍵を持たないため、本文を復号できません

### 4.5 この仕組みでも守られないこと

開発者は、以下の限界を隠さずに開示します。

- **メタデータは保護されません。**「誰が」「いつ」「誰と」やり取りしたか、どのグループに誰がいるか、プロフィール画像は暗号化されておらず、開発者は閲覧可能です
- **プッシュ通知の送信者名は平文で流通します。** Apple の通知サーバーを経由します
- **グループ退出後の鍵の更新を行っていません。** 退出した利用者が退出時点の鍵を保持し続けた場合、その後のメッセージを技術的には復号できる可能性があります
- **公開鍵の照合機能がありません。** 中間者攻撃を利用者が検知する手段を提供していません
- **端末そのものが第三者に渡った場合は保護できません。** 端末のパスコード設定は必ず行ってください
- **受信者による転送・撮影は防げません。** スクリーンショットや画面の撮影を技術的に防ぐ手段はありません
- **暗号技術に将来的な脆弱性が発見される可能性があります。** 将来にわたる安全性を保証するものではありません

